#!/usr/bin/env node
// ============================================================================
// Krishi Sahayak PWA build
//   1. Syncs the monthly datasets from backend/src/data (single source of truth)
//      into web_simulator/data as .json (fetch) and .js (file:// in Android app)
//   2. Stamps the service-worker CACHE_NAME with a content hash so installed apps
//      pick up new code / a new month's data automatically
//   3. Mirrors web_simulator → web_app, public, dist, android assets/pwa
// Usage: npm run build   (from repo root)
// ============================================================================
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = path.join(root, 'web_simulator');
const dataSrc = path.join(root, 'backend', 'src', 'data');
const dataOut = path.join(src, 'data');

const DATASETS = [
  { file: 'crop-variety-almanac.json', global: 'KRISHI_DATA_CROP_ALMANAC', requiredKey: 'stateSuitability' },
  { file: 'soil-zone-atlas.json', global: 'KRISHI_DATA_SOIL_ATLAS', requiredKey: 'soilTypes' }
];

// 1. Datasets
fs.mkdirSync(dataOut, { recursive: true });
for (const ds of DATASETS) {
  const raw = fs.readFileSync(path.join(dataSrc, ds.file), 'utf8');
  const parsed = JSON.parse(raw); // fail the build on invalid JSON
  if (!parsed[ds.requiredKey]) throw new Error(`${ds.file} is missing "${ds.requiredKey}"`);
  fs.writeFileSync(path.join(dataOut, ds.file), raw);
  const jsName = ds.file.replace(/\.json$/, '.js');
  fs.writeFileSync(
    path.join(dataOut, jsName),
    `// Generated by scripts/build_pwa.mjs from backend/src/data/${ds.file} — do not edit.\n` +
    `window.${ds.global} = ${JSON.stringify(parsed)};\n`
  );
  console.log(`✓ data/${ds.file} + data/${jsName}`);
}

// 2. Service-worker cache stamp (hash of every precached asset except sw.js itself)
const swPath = path.join(src, 'sw.js');
let sw = fs.readFileSync(swPath, 'utf8');
const assetList = [...sw.matchAll(/'\.\/([^']+)'/g)].map((m) => m[1]).filter((p) => p && p !== 'sw.js');
const hash = crypto.createHash('sha1');
for (const rel of assetList.sort()) {
  const full = path.join(src, rel);
  if (!fs.existsSync(full)) throw new Error(`sw.js precaches missing file: ${rel}`);
  hash.update(rel).update(fs.readFileSync(full));
}
const stamp = hash.digest('hex').slice(0, 10);
const cacheName = `krishi-sahayak-pwa-${stamp}`;
sw = sw.replace(/const CACHE_NAME = '[^']*';/, `const CACHE_NAME = '${cacheName}';`);
fs.writeFileSync(swPath, sw);
console.log(`✓ sw.js CACHE_NAME = ${cacheName} (${assetList.length} precached assets)`);

// 3. Mirror outputs
const targets = ['public', 'web_app', 'dist', 'android_app/app/src/main/assets/pwa'];
for (const t of targets) {
  const dest = path.join(root, t);
  fs.mkdirSync(dest, { recursive: true });
  fs.cpSync(src, dest, { recursive: true });
}
console.log(`✓ Mirrored web_simulator → ${targets.join(', ')}`);
